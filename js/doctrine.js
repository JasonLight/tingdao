  // cues that the speaker is quoting a saying in order to correct it (suppress warning)
  const REFUTE = /有人(?:誤以為|誤認為|誤會|誤用|誤引|誤傳|說|以為|認為|教導|相信)|有些人|許多人|很多人|常(?:聽|有人|被)|世人(?:說|以為)|俗話|俗語|流行(?:的)?(?:說法|話)|並不是|不是聖經|不是真的|聖經(?:並)?沒有(?:這樣|這麼|這句|說過)|沒有這句|沒有這樣|不是這樣|錯誤的|誤解|迷思|謬論|異端|錯的|不對|不正確|不可信|不要相信|千萬別|別以為|不要以為|不要說|別說|並非|是假的|是謊言|這是錯|其實(?:不是|並不|不)|但是?(?:聖經|其實|實際)|可是(?:聖經|其實)|如果有人說|假如有人說|若有人說|是不是|真的嗎|對嗎|嗎[？?]|[？?]/;
  const ATTRIB = /聖經(?:上|裡|裏|中)?(?:說|記載|寫著|教導|告訴我們)|經上(?:說|記著|寫著)|神的話(?:說|告訴我們)|主(?:耶穌)?說|聖經的教導|聖經就是/;
  const HEDGE = /可能|或許|也許|某種程度|有時候|有時|某些時候|在某些情況|比喻/;

  function sentenceAt(text, i, j) {
    const seps = '。！？!?\n；;';
    let s = i; while (s > 0 && !seps.includes(text[s - 1])) s--;
    let e = j; while (e < text.length && !seps.includes(text[e])) e++;
    return { s, e: Math.min(text.length, e + 1), text: text.slice(s, Math.min(text.length, e + 1)) };
  }

  /** Check text against curated rules. opts.prev = previous text (for refute cues spanning sentences). */
  function check(text, opts) {
    opts = opts || {};
    const out = [];
    for (const r of RULES) {
      for (const re of r.re) {
        const m = re.exec(text);
        if (!m) continue;
        const i = m.index, j = i + m[0].length;
        const sent = sentenceAt(text, i, j);
        // context = sentence with the match itself removed + the tail of previous sentence(s)
        const around = text.slice(sent.s, i) + ' ' + text.slice(j, sent.e);
        const before = (opts.prev ? opts.prev.slice(-30) : '') + text.slice(Math.max(0, sent.s - 40), sent.s);
        if (r.notAfter && r.notAfter.test(text.slice(Math.max(0, i - 3), i))) continue;
        const negated = /(?:不是|並非|並不是|不能|不可|不要|不會|不必|不用|沒有|無法)(?:只)?(?:是)?$/.test(text.slice(Math.max(0, i - 4), i));
        const refuted = negated || REFUTE.test(around) || (text.slice(Math.max(0, i - 24), i) + before.slice(-14)).match(/有人說|有些人說|很多人說|常說|常聽到|俗話說|不要說|別說/);
        // "很多人常說天助自助者，這就是聖經教導我們的" — a soft hearsay cue followed by an explicit endorsement is not a refutation
        let refutedFinal = !!refuted;
        if (refutedFinal && !negated) {
          const rm = REFUTE.exec(around);
          const tail = text.slice(j, sent.e);
          if ((!rm || /^(?:有人說|有人以為|有人認為|有些人|許多人|很多人|常聽|常有人|常被|世人說|世人以為)$/.test(rm[0])) && /這(?:就)?是聖經(?:的)?(?:教導|教訓|說的|所說|真理)|聖經(?:教導|告訴)我們/.test(tail) && !/但|其實|不是|並非|沒有|不對|錯/.test(tail)) refutedFinal = false;
        }
        let c = CONF[r.conf];
        if (r.attributable && ATTRIB.test(sent.text)) c = Math.min(0.95, c + 0.1);
        if (HEDGE.test(around)) c -= 0.15;
        out.push({
          ruleId: r.id, level: r.level, title: r.title, heard: m[0], sentence: sent.text.trim(), start: i, end: j,
          why: r.why, verses: r.verses, correct: r.correct, conf: Math.max(0.2, Math.round(c * 100) / 100), suppressed: refutedFinal, src: 'rule',
        });
        break;
      }
    }
    return out;
  }

  /** Turn a near-quote match from TingdaoVerses.analyze into a misquote warning object (or null if not meaningful). */
  function misquoteWarning(m, verseLabel, verseText) {
    if (m.kind !== 'near') return null;
    const real = m.diffs.filter((d) => (d.from + d.to).length > 0);
    if (!real.length) return null;
    const changed = real.reduce((n, d) => n + Math.max(d.from.length, d.to.length), 0);
    let conf = 0.45 + (m.framed ? 0.1 : 0) + (m.isRef ? 0.1 : 0) + (m.negation ? 0.1 : 0) + Math.min(0.15, changed * 0.03);
    conf = Math.min(0.85, conf);
    const lst = real.slice(0, 3).map((d) => (d.from ? `聽到「${d.from}」` : '少了') + (d.to ? (d.from ? '，經文是「' + d.to + '」' : '「' + d.to + '」') : '，經文沒有這段')).join('；');
    return {
      ruleId: 'misquote', level: 'misquote', title: `引用與${verseLabel}有出入`, heard: m.heard, sentence: m.heard,
      why: `這段話很像${verseLabel}，但有幾處不同：${lst}。` + (m.negation ? '差異涉及否定詞（不／沒／無…），意思可能被改變或省略。' : '') + '也可能是語音辨識誤差或講員的意譯，請對照經文確認。',
      verses: [verseLabel], correct: verseText, conf: Math.round(conf * 100) / 100, suppressed: false, src: 'quote', diffs: real,
    };
  }

